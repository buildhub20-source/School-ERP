/**
 * One-command POC: runs the whole product with mock data from JSON — no database, no external services.
 *
 *   npm run poc            Next.js dev server on :3100 (POC_PORT to change)
 *   npm run poc -- --prod  builds and serves the production bundle
 *   npm run poc:reset      throws away all changes (next start reloads the original mock data)
 *
 * Data: data/demo-data.json is the pristine mock school; every change is saved to .poc/data.json (src/lib/json-db).
 * Payments use the built-in sandbox checkout, SMS/email/WhatsApp land in the in-app Outbox, the parent/driver login
 * code is 123456, and bus GPS is simulated (MOCK_GPS) so the live map and parent bus tracker move.
 */
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP_PORT = Number(process.env.POC_PORT ?? 3100);
const prod = process.argv.includes("--prod");
const workingFile = path.join(root, ".poc", "data.json");

if (process.argv.includes("--reset")) {
  fs.rmSync(workingFile, { force: true });
  console.log("[poc] changes discarded. The next `npm run poc` starts from the original mock data (data/demo-data.json).");
  process.exit(0);
}

// process.env wins over .env in Next.js, so .env never has to be edited for the POC.
const env = {
  ...process.env,
  APP_URL: process.env.APP_URL ?? `http://localhost:${APP_PORT}`,
  DEMO_OTP: process.env.DEMO_OTP ?? "123456",
  PAYMENTS_SANDBOX: "true",
  MOCK_GPS: process.env.MOCK_GPS ?? "true",
  RUN_SCHEDULER: "true",
  NEXT_TELEMETRY_DISABLED: "1",
};
// Note: in dev mode Next.js keeps every compiled page in memory and restarts itself near its heap limit after many
// pages have been opened (data is saved first, nothing is lost). For demos use --prod: pages are pre-built and fast.

/** A matching .env, so plain `npm run dev` behaves the same. */
const envFile = path.join(root, ".env");
if (!fs.existsSync(envFile) || /DATABASE_URL=.*54329/.test(fs.readFileSync(envFile, "utf8"))) {
  const keys = ["APP_URL", "DEMO_OTP", "PAYMENTS_SANDBOX", "MOCK_GPS", "RUN_SCHEDULER"];
  fs.writeFileSync(envFile, `# Generated by npm run poc (JSON mock-data POC, no database). Safe to edit.\n${keys.map((k) => `${k}="${env[k]}"`).join("\n")}\n`);
  console.log("[poc] wrote .env");
}

const run = (args) => spawnSync("npx", args, { cwd: root, env, stdio: "inherit", shell: process.platform === "win32" });

if (!fs.existsSync(path.join(root, "node_modules", ".prisma", "client", "index.js"))) run(["prisma", "generate"]); // types + schema metadata only
if (prod && run(["next", "build"]).status !== 0) process.exit(1);

console.log(`\n[poc] ${fs.existsSync(workingFile) ? "continuing with your saved changes (.poc/data.json)" : "starting from the original mock data"}`);
console.log(`[poc] open http://localhost:${APP_PORT}  —  Super Admin: superadmin@school.test / Admin@12345  ·  staff: Staff@12345  ·  parent/driver OTP: ${env.DEMO_OTP}\n`);
const app = spawn("npx", ["next", prod ? "start" : "dev", "-p", String(APP_PORT)], { cwd: root, env, stdio: "inherit", shell: process.platform === "win32" });

let stopping = false;
const stop = () => {
  if (stopping) return;
  stopping = true;
  // With shell:true on Windows, app.kill() only ends the cmd wrapper and leaves Next.js running: kill the whole tree.
  if (process.platform === "win32") spawnSync("taskkill", ["/pid", String(app.pid), "/T", "/F"], { stdio: "ignore" });
  else app.kill("SIGINT");
  process.exit(0);
};
process.on("SIGINT", stop);
process.on("SIGTERM", stop);
app.on("exit", () => process.exit(0));
